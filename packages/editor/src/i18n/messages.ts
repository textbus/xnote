export function normalizeXnoteLocale(locale: string): 'zh-CN' | 'en-US' {
  const l = locale.trim().toLowerCase()
  if (l === 'en' || l === 'en-us' || l.startsWith('en-')) {
    return 'en-US'
  }
  if (l === 'zh' || l === 'zh-cn' || l.startsWith('zh-')) {
    return 'zh-CN'
  }
  return 'zh-CN'
}
